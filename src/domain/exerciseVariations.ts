/**
 * Storage key for session cycles (Cycle A vs Cycle B)
 */
export const STORAGE_KEY_SESSION_CYCLES = 'workout_app_session_cycles_v1';
export const STORAGE_KEY_CUSTOM_VARIATIONS = 'workout_app_custom_variations_v1';

/**
 * Retrieve all available variations for a given exercise ID (or its baseExerciseId).
 */
export function getExerciseVariations(exerciseIdOrBase: string): ExerciseVariation[] {
  const cleanId = exerciseIdOrBase
    .replace(/__side_(left|right)/g, '')
    .replace(/_(lower_a|upper_a|lower_b|upper_b|daily_abs)/g, '');
  return EXERCISE_VARIATIONS[cleanId] || EXERCISE_VARIATIONS[exerciseIdOrBase] || [];
}

/**
 * Get the variation corresponding to a specific cycle ('A' or 'B').
 */
export function getCycleVariation(
  exerciseIdOrBase: string,
  cycle: WorkoutCycle
): ExerciseVariation | undefined {
  const variations = getExerciseVariations(exerciseIdOrBase);
  if (variations.length === 0) return undefined;

  const match = variations.find((v) => v.cycleAffiliation === cycle || v.cycleAffiliation === 'Both');
  return match || variations[0];
}

/**
 * Convert an ExerciseVariation into a WorkoutExercise object.
 */
export function variationToWorkoutExercise(
  variation: ExerciseVariation,
  baseExercise: WorkoutExercise
): WorkoutExercise {
  return {
    ...baseExercise,
    id: baseExercise.id,
    baseExerciseId: variation.baseExerciseId,
    name: variation.name,
    tier: variation.tier,
    targetSets: variation.targetSets,
    targetReps: variation.targetReps,
    tempo: variation.tempo,
    restSeconds: variation.restSeconds,
    equipment: variation.equipment,
    defaultWeight: variation.defaultWeightLbs ?? baseExercise.defaultWeight,
    defaultWeightLbs: variation.defaultWeightLbs ?? baseExercise.defaultWeightLbs,
    muscleGroups: variation.muscleGroups,
    biomechanicalRationale: variation.scientificRationale,
    progressionRule: variation.progressionRule,
    regression: variation.regression ?? baseExercise.regression,
    isUnilateral: variation.isUnilateral ?? baseExercise.isUnilateral,
    llpEligible: variation.llpEligible ?? baseExercise.llpEligible,
    llpProtocolNotes: variation.llpProtocolNotes ?? baseExercise.llpProtocolNotes,
  };
}

/**
 * Loads stored cycle wave configuration per session from localStorage.
 */
export function loadSessionCycles(): Record<string, WorkoutCycle> {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_SESSION_CYCLES);
    if (!raw) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

/**
 * Saves cycle wave configuration for a session.
 */
export function saveSessionCycle(sessionId: string, cycle: WorkoutCycle): void {
  try {
    const current = loadSessionCycles();
    current[sessionId] = cycle;
    localStorage.setItem(STORAGE_KEY_SESSION_CYCLES, JSON.stringify(current));
  } catch {
    // safe fallback
  }
}

